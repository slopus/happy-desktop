#!/usr/bin/env node
// Writes src/avatarShader/avatarShaderTable.ts: what the live shader needs to
// draw each of the 200 avatar placeholders (its effect, colours, layout, angle
// and phase), converted from happy-ios's `AvatarShaderTable.swift`. That table
// is made by happy-ios's `scripts/generate-avatar-shader-table.mjs` from
// @craftedstudios/shaders' own `resolve` and `angleOf`, so desktop draws the
// same placeholder for the same index as the phone, to the digit.
//
//   node packages/happy-desktop-ui/scripts/generate-avatar-shader-table.mjs \
//     <happy>/packages/happy-ios/Sources/HappyLayout/AvatarShaderTable.swift
//
// @craftedstudios/shaders is MIT, Copyright (c) 2026 Crafted Studios; its
// notice travels with the shader (licenses/Crafted-Studios-Shaders-MIT.txt).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source = process.argv[2];
if (!source) throw new Error("Pass the path to happy-ios's AvatarShaderTable.swift");
const swift = readFileSync(source, "utf8");
const version = /@craftedstudios\/shaders (\S+) \(MIT/.exec(swift)?.[1];
if (!version) throw new Error("The Swift table does not name its @craftedstudios/shaders version");

const numbers = (text) => text.split(",").map((value) => Number(value.trim()));
const rows = [
    ...swift.matchAll(
        /\.init\(effect: \.(\w+), colors: \[(.*?)\], layout: SIMD4\((.*?)\), angle: (\S+), phase: (\S+)\),/g,
    ),
].map(([, effect, colors, layout, angle, phase]) => ({
    effect,
    colors: [...colors.matchAll(/SIMD3\((.*?)\)/g)].map(([, rgb]) => numbers(rgb)),
    layout: numbers(layout),
    angle: Number(angle),
    phase: Number(phase),
}));
if (rows.length !== 200) throw new Error(`The Swift table has ${rows.length} rows, not 200`);
for (const row of rows) {
    if (row.colors.length !== 4 || row.colors.some((rgb) => rgb.length !== 3))
        throw new Error(`A row has colours other than four RGB triples: ${JSON.stringify(row)}`);
    if (row.layout.length !== 4 || [...row.layout, row.angle, row.phase].some(Number.isNaN))
        throw new Error(`A row has an unreadable number: ${JSON.stringify(row)}`);
}

const list = (values) => `[${values.join(", ")}]`;
const out = `// Generated by scripts/generate-avatar-shader-table.mjs from happy-ios's
// AvatarShaderTable.swift, itself from @craftedstudios/shaders ${version}
// (MIT, Copyright (c) 2026 Crafted Studios). Do not edit.

import type { AvatarShaderParameters } from "./avatarShader";

/** Each placeholder's drawing, in the pictures' order. */
export const avatarShaderTable: readonly AvatarShaderParameters[] = [
${rows
    .map(
        (row) =>
            `    { effect: "${row.effect}", colors: [${row.colors.map(list).join(", ")}], layout: ${list(row.layout)}, angle: ${row.angle}, phase: ${row.phase} },`,
    )
    .join("\n")}
];
`;
writeFileSync(join(import.meta.dirname, "../src/avatarShader/avatarShaderTable.ts"), out);
console.log(`${rows.length} placeholders from @craftedstudios/shaders ${version}`);
