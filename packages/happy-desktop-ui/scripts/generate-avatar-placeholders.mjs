#!/usr/bin/env node
// Writes the 200 avatar placeholder stills into src/assets/avatar-placeholders/
// from the pictures happy-ios and happy-android ship, so desktop shows the same
// still for the same index as the phone; and, from happy-ios's
// AvatarShaderTable.swift, src/avatarPlaceholderBackdrops.ts, each one's
// colours as the gradient shown until its still is decoded, and
// src/avatarShader/avatarShaderTable.ts, what the live shader draws each with
// under Animated avatars.
//
// The phone's pictures are 384px; desktop draws a placeholder at most 44 CSS
// pixels across, so each is scaled to 128px, which still covers it at 2x.
//
//   node packages/happy-desktop-ui/scripts/generate-avatar-placeholders.mjs <happy>
//
// @craftedstudios/shaders is MIT, Copyright (c) 2026 Crafted Studios; its
// notice travels with the pictures (licenses/Crafted-Studios-Shaders-MIT.txt).
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";
import { avatarShaderTableRead } from "./avatarShader/avatarShaderTable.mjs";

const COUNT = 200;
const PIXELS = 128;

const happy = process.argv[2];
if (!happy) throw new Error("Pass the path to a checkout of the happy repository");
const ios = join(happy, "packages/happy-ios/Sources");

const out = join(import.meta.dirname, "../src/assets/avatar-placeholders");
mkdirSync(out, { recursive: true });
for (let index = 0; index < COUNT; index += 1) {
    const name = `avatar-placeholder-${String(index + 1).padStart(3, "0")}.webp`;
    await sharp(join(ios, "HappyUI/Resources/AvatarPlaceholders", name))
        .resize(PIXELS, PIXELS, { kernel: "lanczos3" })
        .webp({ quality: 82, effort: 6 })
        .toFile(join(out, name));
}
console.log(`${COUNT} placeholders at ${PIXELS}px`);

const { version, rows } = avatarShaderTableRead(happy);
const css = ([red, green, blue]) =>
    `rgb(${Math.round(red * 255)} ${Math.round(green * 255)} ${Math.round(blue * 255)})`;
// Topography's fourth colour is unused, and its ground is its third.
const backdrops = rows.map(
    ({ effect, colors }) =>
        `linear-gradient(135deg, ${css(colors[0])}, ${css(effect === "topography" ? colors[2] : colors[3])})`,
);
writeFileSync(
    join(import.meta.dirname, "../src/avatarPlaceholderBackdrops.ts"),
    `// Generated by scripts/generate-avatar-placeholders.mjs from happy-ios's
// AvatarShaderTable.swift, itself from @craftedstudios/shaders ${version}
// (MIT, Copyright (c) 2026 Crafted Studios). Do not edit.

/** Each placeholder's first and last colour as a gradient, in the pictures' order. */
export const avatarPlaceholderBackdrops: readonly string[] = [
${backdrops.map((backdrop) => `    "${backdrop}",`).join("\n")}
];
`,
);

const list = (values) => `[${values.join(", ")}]`;
writeFileSync(
    join(import.meta.dirname, "../src/avatarShader/avatarShaderTable.ts"),
    `// Generated by scripts/generate-avatar-placeholders.mjs from happy-ios's
// AvatarShaderTable.swift, itself from @craftedstudios/shaders ${version}
// (MIT, Copyright (c) 2026 Crafted Studios). Do not edit.

import type { AvatarShaderParameters } from "./avatarShader";

/** Each placeholder's drawing, in the pictures' order. */
export const avatarShaderTable: readonly AvatarShaderParameters[] = [
${rows
    .map(
        (row) =>
            `    { effect: "${row.effect}", colors: [${row.colors.map(list).join(", ")}], layout: ${list(row.layout)}, angle: ${row.angle}, phase: ${row.phase} },`,
    )
    .join("\n")}
];
`,
);
